#!/usr/bin/env node
// Build the public deck of a lecture from its full deck.
//
//   data/lectures/<lecture>_full.json     the presenter's deck; ignored by git
//   tools/public-rules/<lecture>.js       the rules for that lecture; ignored by git
//   data/lectures/<lecture>.json          the public deck; tracked and published
//
// The repository is public. Department data that is not yet published, the
// internals a security review would keep inside, and the names of people
// who did not ask to be named stay in the full deck. The rules file writes
// the public deck from it: slides dropped, fields replaced, sentences
// scrubbed, glossary entries removed, and then assertions that fail the
// build if anything on its list survives. The rules name the material they
// remove, so they are ignored by git along with the full deck; this script
// is the generic part.
//
// Edit the full deck, never the public one; rebuild with
//     node tools/build-public-deck.js [lecture]
// and the public deck follows.
//
// A rules module exports one function, called with a context:
//   { deck, slide(id), setField(obj, key, from, to, where),
//     replaceIn(obj, key, from, to, where), log(msg), fail(msg) }
// `setField` and `replaceIn` refuse to run against text that differs from
// `from`, so a change in the full deck cannot silently leave internal
// material in the public deck.

const fs = require('fs');
const path = require('path');

const lecture = process.argv[2] || 'ai_infrastructure';
const ROOT = path.join(__dirname, '..');
const FULL = path.join(ROOT, 'data', 'lectures', lecture + '_full.json');
const RULES = path.join(__dirname, 'public-rules', lecture + '.js');
const OUT = path.join(ROOT, 'data', 'lectures', lecture + '.json');

function fail(msg) { console.error('build-public-deck: ' + msg); process.exit(1); }
if (!fs.existsSync(FULL)) fail('no full deck at ' + path.relative(ROOT, FULL) + '. The public deck is built from it; copy the presenter\'s deck there first.');
if (!fs.existsSync(RULES)) fail('no rules at ' + path.relative(ROOT, RULES) + '. They live with the full deck, off the repository.');

const deck = JSON.parse(fs.readFileSync(FULL, 'utf8'));
const byId = {}; deck.slides.forEach(s => { byId[s.id] = s; });
const log = [];

const ctx = {
    deck,
    fail,
    log: msg => log.push(msg),
    slide(id) { if (!byId[id]) fail('no slide ' + id); return byId[id]; },
    setField(obj, key, from, to, where) {
        const same = typeof from === 'object' ? JSON.stringify(obj[key]) === JSON.stringify(from) : obj[key] === from;
        if (!same) fail(where + '.' + key + ': expected "' + String(from).slice(0, 70) + '…", found "' + String(obj[key]).slice(0, 70) + '…"');
        obj[key] = to; log.push('set ' + where + '.' + key);
    },
    replaceIn(obj, key, from, to, where) {
        const s = obj[key];
        if (typeof s !== 'string' || s.split(from).length !== 2) fail(where + '.' + key + ': anchor not found once: "' + from.slice(0, 70) + '…"');
        obj[key] = s.replace(from, to); log.push('replace in ' + where + '.' + key);
    }
};

require(RULES)(ctx);

deck.slides = deck.slides.filter(Boolean);
deck.meta.publicBuild = { from: lecture + '_full.json', tool: 'tools/build-public-deck.js', note: 'Generated. Edit the full deck and rebuild; do not edit this file.' };
fs.writeFileSync(OUT, JSON.stringify(deck, null, 2) + '\n');
console.log('public deck → ' + path.relative(ROOT, OUT));
console.log('  slides: ' + deck.slides.length + ' (' + deck.slides.filter(s => !s.isOptional).length + ' core) · glossary: ' + (deck.meta.glossary || []).length);
log.forEach(l => console.log('  · ' + l));
